export const GLYPH_W = 5;
export const GLYPH_H = 7;
const GAP = 1; // cells between glyphs

export function textWidthCells(text: string): number {
  return text.length * (GLYPH_W + GAP) - GAP;
}

export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  centerX: number,
  topY: number,
  cell: number,
  color: string,
): void {
  ctx.fillStyle = color;
  const originX = Math.round(centerX - (textWidthCells(text) * cell) / 2);
  const originY = Math.round(topY);
  let cx = originX;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    for (let row = 0; row < GLYPH_H; row++) {
      for (let col = 0; col < GLYPH_W; col++) {
        if (glyph[row][col] === "#") {
          ctx.fillRect(cx + col * cell, originY + row * cell, cell, cell);
        }
      }
    }
    cx += (GLYPH_W + GAP) * cell;
  }
}
